#!/usr/bin/env bash
#
# Install WordPress and WooCommerce into tests/tmp/wordpress for integration tests.
# Environment variables (set by CI or the developer):
#   WC_VERSION   WooCommerce version to download (default: 10.9.4)
#   WP_DB_HOST   Database host (default: 127.0.0.1)
#   WP_DB_NAME   Database name (default: wordpress_test)
#   WP_DB_USER   Database user (default: root)
#   WP_DB_PASS   Database password (default: root)

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TMPDIR="${ROOT}/tests/tmp"
WP_DIR="${TMPDIR}/wordpress"

WC_VERSION="${WC_VERSION:-10.9.4}"
WP_DB_HOST="${WP_DB_HOST:-127.0.0.1}"
WP_DB_NAME="${WP_DB_NAME:-wordpress_test}"
WP_DB_USER="${WP_DB_USER:-root}"
WP_DB_PASS="${WP_DB_PASS:-root}"

# Use wp-phpunit's bundled WordPress version.
#
# Checked via wp-settings.php's presence, not merely $WP_DIR's existence:
# $WP_DIR is a symlink to "." (tests/tmp itself, see below), and CI's own
# actions/cache step caches exactly $WP_DIR ("tests/tmp/wordpress") — which,
# being a symlink, serializes to a tiny (~194 byte) cache entry containing
# only the symlink itself, never the real WordPress core files that live in
# its target (tests/tmp/, the parent, outside the cached path). A cold
# checkout that restores that cache ends up with a $WP_DIR that "exists" as
# a directory (the symlink resolves) but is actually empty — `[ ! -d ]`
# alone would then wrongly skip the entire download below.
if [ ! -f "$WP_DIR/wp-settings.php" ]; then
	echo "Setting up WordPress test environment in $WP_DIR..."

	# wp-phpunit publishes one package version per WordPress core release,
	# using WordPress's own version string verbatim (e.g. package 7.0.2 <->
	# WP core 7.0.2) — the package ships no wordpress-core/ directory or
	# wp-phpunit.json manifest of its own (confirmed absent from every
	# tagged release, not merely this one), so the resolved package version
	# itself (from Composer's own installed.json, never a manifest file
	# inside the package) is WordPress core's version to download.
	WP_VERSION=$(php -r '
		$installed = json_decode(file_get_contents("'"$ROOT"'/vendor/composer/installed.json"), true);
		foreach ($installed["packages"] as $package) {
			if ("wp-phpunit/wp-phpunit" === $package["name"]) {
				echo $package["version"];
				exit;
			}
		}
	')
	echo "WordPress version: $WP_VERSION"

	mkdir -p "$TMPDIR"
	cd "$TMPDIR"

	# Download and extract WordPress core from wp-phpunit.
	php -r "
		\$core_dir = '$ROOT/vendor/wp-phpunit/wp-phpunit/wordpress-core/';
		if ( is_dir( \$core_dir ) ) {
			// wp-phpunit bundles WordPress; use it.
			\$src = rtrim( \$core_dir, '/' );
		} else {
			// Download from wordpress.org.
			\$url = 'https://github.com/WordPress/WordPress/archive/$WP_VERSION.tar.gz';
			\$tar = tempnam( sys_get_temp_dir(), 'wp-' );
			copy( \$url, \$tar );
			exec( 'tar --strip-components=1 -xzf ' . escapeshellarg( \$tar ) . ' -C . || true' );
			unlink( \$tar );
			\$src = '.';
		}
		if ( ! is_file( 'wp-load.php' ) ) {
			echo \"Error: WordPress core not found in \$src.\\n\";
			exit( 1 );
		}
	"

	# The download above always extracts (--strip-components=1) directly
	# into $TMPDIR itself, never into a "wordpress-$WP_VERSION" subdirectory
	# — confirmed against the actual archive layout, not assumed — so the
	# WP_DIR symlink always points at $TMPDIR itself ("."), never a
	# version-named sibling.
	if [ -d "$WP_DIR" ] || [ -L "$WP_DIR" ]; then
		rm -rf "$WP_DIR"
	fi
	ln -s "." "$WP_DIR"
fi

# Create wp-tests-config.php if needed.
CONFIG_FILE="${ROOT}/tests/wp-tests-config.php"
if [ ! -f "$CONFIG_FILE" ]; then
	cat > "$CONFIG_FILE" << 'EOF'
<?php
/**
 * Test database configuration (generated by tests/bin/install-wp.sh).
 */

define( 'DB_NAME', getenv( 'WP_DB_NAME' ) ?: 'wordpress_test' );
define( 'DB_USER', getenv( 'WP_DB_USER' ) ?: 'root' );
define( 'DB_PASSWORD', getenv( 'WP_DB_PASS' ) ?: 'root' );
define( 'DB_HOST', getenv( 'WP_DB_HOST' ) ?: '127.0.0.1' );
define( 'DB_CHARSET', 'utf8' );
define( 'DB_COLLATE', '' );

$_SERVER['HTTP_HOST'] = 'wordpress.test';
$_SERVER['SCRIPT_NAME'] = '/index.php';
$_SERVER['SCRIPT_FILENAME'] = __DIR__ . '/tmp/wordpress/index.php';
$_SERVER['SERVER_NAME'] = 'wordpress.test';

define( 'WP_TESTS_DOMAIN', 'wordpress.test' );
define( 'WP_TESTS_EMAIL', 'admin@wordpress.test' );
define( 'WP_TESTS_TITLE', 'WordPress Tests' );
define( 'WP_PHP_BINARY', 'php' );
define( 'ABSPATH', __DIR__ . '/tmp/wordpress/' );

// Suppress core error handling in tests.
define( 'WP_DEBUG_DISPLAY', false );

require_once ABSPATH . 'wp-settings.php';
EOF
fi

# Download WooCommerce if needed.
if [ ! -d "$WP_DIR/wp-content/plugins/woocommerce" ]; then
	echo "Installing WooCommerce $WC_VERSION..."
	mkdir -p "$WP_DIR/wp-content/plugins"
	cd "$WP_DIR/wp-content/plugins"

	TMPZIP=$(mktemp)

	if [ "$WC_VERSION" = "latest" ]; then
		# No built release asset exists for an unreleased trunk build —
		# fall back to the source archive (the whole monorepo: packages/,
		# plugins/, tools/, ...), then promote the nested plugin directory.
		curl -sSLo "$TMPZIP" "https://github.com/woocommerce/woocommerce/archive/refs/heads/trunk.zip"
		unzip -q "$TMPZIP"
		rm "$TMPZIP"

		if [ -d "woocommerce-trunk" ]; then
			mv "woocommerce-trunk" woocommerce
		fi

		if [ -f "woocommerce/plugins/woocommerce/woocommerce.php" ]; then
			mv "woocommerce/plugins/woocommerce" woocommerce-plugin-only
			rm -rf woocommerce
			mv woocommerce-plugin-only woocommerce
		fi
	else
		# The tagged source archive is the whole monorepo and, unlike the
		# release asset below, ships no pre-built vendor/ — WooCommerce
		# itself then reports "installation incomplete" and never boots.
		# The GitHub Release's own "woocommerce.zip" asset is the actual
		# built plugin (already the standard single-plugin zip layout,
		# top-level directory "woocommerce/", vendor/ included) — the
		# correct artifact for a runtime install, exactly what a site
		# operator would download from wordpress.org.
		curl -sSLo "$TMPZIP" "https://github.com/woocommerce/woocommerce/releases/download/$WC_VERSION/woocommerce.zip"
		unzip -q "$TMPZIP"
		rm "$TMPZIP"
	fi
fi

echo "WordPress test environment ready."
